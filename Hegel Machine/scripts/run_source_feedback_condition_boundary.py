#!/usr/bin/env python3
"""Record the condition boundary of the real source-feedback fixture.

The five paid prefixes are generated by ``ConflictLagEnvironment`` from the
existing fixture.  Each arm uses a fresh copy of the real source library and
the same continuation budget.  The transition rows are deterministic, while
the search seed can change the candidate/refit path.  The seed sweep measures
search variation; it does not create independent task data.
"""

from copy import deepcopy
from dataclasses import asdict
import json
from pathlib import Path
import sys


ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "artifacts" / "source_feedback_condition_boundary_20261004"
sys.path.insert(0, str(ROOT / "src"))
sys.path.insert(0, str(ROOT / "tests"))


def _fixtures():
    from test_cognition_unified_source_returns import failed_successor, source_competition

    case = failed_successor.__wrapped__()
    good, _warm, cold = source_competition.__wrapped__(case)[1:]
    return case, good, cold


def _lab_class():
    from test_cognition_conflict_transfer_refit import ConflictLagEnvironment
    from hegel_machine.cognition.measurement_lab import MeasurementBatch

    class NumericConflictLab(ConflictLagEnvironment):
        channels = ()

        def spec_for(self, channels=()):
            assert not channels
            return self.spec

        def acquire(self, probe, channels=()):
            assert not channels
            rows = self.observe(probe)
            return MeasurementBatch(rows, len(rows), 0, ())

    return NumericConflictLab


def _prefixes(case):
    probes = case["spec"].initial_probes
    available = case["spec"].available_probes
    return {
        "initial": probes,
        "initial_plus_query00": probes + (available[0],),
        "initial_plus_query02": probes + (available[2],),
        "single_query00": (available[0],),
        "mixed_initial00_initial01_query00": (probes[0], probes[1], available[0]),
    }


def _previous(case, probes, lab):
    from hegel_machine.cognition.evaluation import initial_prediction, loss
    from hegel_machine.cognition.language import Program

    batches, rows = [], []
    for probe in probes:
        measured = lab.observe(probe)
        rows.extend(measured)
        batches.append({"probe": asdict(probe), "channels": [],
                        "observations": [asdict(row) for row in measured]})
    previous = deepcopy(case["previous"])
    previous["batches"] = batches
    previous["fallback"] = initial_prediction(rows, .5)
    previous["selection_loss"] = loss(
        Program.from_dict(previous["program"]), rows, previous["fallback"], .5)
    return previous, len(rows)


def _run(case, source_id, library, previous, seed, label):
    from hegel_machine.cognition.models import ResearchConfig, SearchBudget
    from hegel_machine.cognition.unified_research import UnifiedResearchAgent
    from hegel_machine.cognition.unified_revisits import offer_successor_knowledge

    config = ResearchConfig(observation_budget=100, compute_budget=20_000,
        minimum_improvement=1e-7, max_rounds=1, active_probes=False,
        risk_learning=False, seed=seed, max_candidates=2)
    lab = _lab_class()(case["spec"])
    agent = UnifiedResearchAgent(config, library=library, measurement_budget=0)
    offer = offer_successor_knowledge(agent, lab, previous, {source_id}, SearchBudget(4_000))
    if offer is None:
        raise RuntimeError(f"real offer missing for {label} under {seed}")
    report = agent.run(lab, previous=previous, continuation_candidate=offer["candidate"])
    records = [row for row in report["knowledge_return"]["returns"]
               if row["source_id"] == source_id]
    if len(records) != 1:
        raise AssertionError(f"expected one source return, got {len(records)}")
    record = records[0]
    return {
        "source": label,
        "seed": seed,
        "paid_rows": sum(len(batch["observations"]) for batch in previous["batches"]),
        "old_evidence_gain": offer["old_evidence_gain"],
        "paired_gain": record["paired_gain"],
        "retained": record["retained"],
        "confirmation_status": record.get("confirmation_status", "confirmed"),
        "final_status": record.get("final_status"),
        "status": report["status"],
        "visit_costs": report["visit_costs"],
        "condition": record["condition"],
        "external_model_calls": 0,
    }


def main():
    case, good, cold = _fixtures()
    sources = [("bad", case["source_id"]), ("good", good)]
    seeds = (1237, 1238, 131, 154, 2024)
    rows = []
    for label, probes in _prefixes(case).items():
        for seed in seeds:
            for source_label, source_id in sources:
                from hegel_machine.cognition.memory import KnowledgeLibrary

                library = KnowledgeLibrary.from_dict(deepcopy(cold.library.to_dict()))
                previous, row_count = _previous(case, probes, _lab_class()(case["spec"]))
                result = _run(case, source_id, library, previous, seed, source_label)
                assert result["paid_rows"] == row_count
                expected_confirmation = ("confirmed" if result["retained"] and result["status"] == "completed"
                                         else "provisional" if result["retained"] else "rejected")
                assert result["confirmation_status"] == expected_confirmation
                result["condition_label"] = label
                rows.append(result)
    OUT.mkdir(parents=True, exist_ok=True)
    payload = {
        "status": "complete",
        "protocol": {
            "fixture": "failed_successor + source_competition",
            "conditions": list(_prefixes(case)),
            "seeds": list(seeds),
            "same_budget": True,
            "rows_are_real_environment_outputs": True,
            "seed_sweep_is_search_variation_audit": True,
            "independent_task_data": False,
            "external_model_calls": 0,
        },
        "results": rows,
    }
    path = OUT / "results.json"
    path.write_text(json.dumps(payload, indent=2, ensure_ascii=False) + "\n")
    print(json.dumps({"status": payload["status"], "rows": len(rows),
                      "output": str(path.relative_to(ROOT))}, ensure_ascii=False))


if __name__ == "__main__":
    main()
