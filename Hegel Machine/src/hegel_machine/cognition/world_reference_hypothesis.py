def _declaration(value):
    hypothesis = deepcopy(value)
    name = hypothesis.get("id")
    if not isinstance(name, str) or not re.fullmatch(r"[A-Za-z][A-Za-z0-9_]*", name):
        raise ValueError("hypothesis id must start with a letter and use letters, numbers or underscores")
    if not isinstance(hypothesis.get("basis"), list) or not hypothesis["basis"]:
        raise ValueError("hypothesis basis must contain at least one Program AST expression")
    for expression in hypothesis["basis"]:
        Program.from_dict(expression)
    if "fit_tolerance" in hypothesis:
        tolerance = float(hypothesis["fit_tolerance"])
        if not isfinite(tolerance) or tolerance < 0:
            raise ValueError("fit_tolerance must be a finite nonnegative MSE in Hz squared")
        hypothesis["fit_tolerance"] = tolerance
    for feature, measurement in hypothesis.get("measurements", {}).items():
        if not feature or not measurement.get("instrument"):
            raise ValueError("each measurement needs a feature name and a public instrument name")
        pattern = re.compile(measurement["pattern"])
        group = measurement.get("group", 1)
        if not isinstance(group, int) or not 0 <= group <= pattern.groups:
            raise ValueError("measurement group must select an existing regex capture")
    return hypothesis


def _retain_declaration(source, hypothesis):
    assignment = next((node for node in ast.parse(source).body
        if isinstance(node, ast.Assign) and any(isinstance(target, ast.Name)
            and target.id == "ESTIMATORS" for target in node.targets)), None)
    if assignment is None:
        raise ValueError("this procedure has no ESTIMATORS declaration; select the reference-calibration procedure")
    estimators = ast.literal_eval(assignment.value)
    previous = next((item for item in estimators if item["id"] == hypothesis["id"]), None)
    if previous is not None:
        if previous != hypothesis:
            raise ValueError("that hypothesis id already records a different declaration; use a new id for the revision")
        return source
    lines = source.splitlines(keepends=True)
    replacement = "ESTIMATORS = " + pformat((*estimators, hypothesis), width=100, sort_dicts=False) + "\n"
    lines[assignment.lineno - 1:assignment.end_lineno] = [replacement]
    return "".join(lines)


def _paid_family_check(agent, laboratory, state, hypothesis):
    """Reuse paid response constraints before buying a proposed point trial."""
    refreshed = deepcopy(state)
    refresh_response_evidence(refreshed, agent.observations, laboratory.public_observation(), [hypothesis])
    responses = refreshed.get("response_settings", [])
    table = refreshed.get("research_table", {})
    rows = {row["crystal"]: row for group in ("references", "targets") for row in table.get(group, [])}
    required = set().union(*(Program.from_dict(term).required_features() for term in hypothesis["basis"]))
    numbers = {response["crystal"] for response in responses}
    if not responses or any(number not in rows or not required <= rows[number]["measurements"].keys()
                            for number in numbers):
        return None
    features = {number: {name: rows[number]["measurements"][name]["value"] for name in required}
                for number in sorted(numbers)}
    started = monotonic()
    try:
        check = query_response_family(features, responses, hypothesis, queries=(),
                                      branch_limit=None, compute_limit=QUERY_ALLOWANCE)
    finally:
        agent.costs["python_execution_seconds"] += monotonic() - started
    agent.costs["research_compute_units"] += check["compute_cost"]
    check.update(features={str(number): values for number, values in features.items()},
        responses=deepcopy(responses), evidence=sorted(
            {index for response in responses for index in response.get("evidence", [])}
            | {rows[number]["measurements"][name]["evidence"] for number in numbers for name in required}))
    state["research_table"] = refreshed["research_table"]
    state["response_settings"] = responses
    state.setdefault("family_history_checks", {})[hypothesis["id"]] = deepcopy(check)
    return check


def _reuse_paid_family_exclusions(agent, laboratory, state, source):
    """Carry this world's paid full-family exclusions into the point-trial filter."""
    estimators = next(ast.literal_eval(node.value) for node in ast.parse(source).body
        if isinstance(node, ast.Assign) and any(isinstance(target, ast.Name)
            and target.id == "ESTIMATORS" for target in node.targets))
    refreshed = deepcopy(state)
    refresh_response_evidence(refreshed, agent.observations, laboratory.public_observation(), estimators)
    retained = reuse_paid_family_exclusions(refreshed, estimators)
    state['family_history_checks'] = refreshed['family_history_checks']
    return list(retained)


def execute_reference_hypothesis(agent, laboratory, arguments):
    """Declare a candidate and return the existing procedure's measured feedback."""
    hypothesis = _declaration(arguments["hypothesis"])
    path = arguments["path"]
    source_path = agent.workspace / path
    source = _retain_declaration(source_path.read_text(encoding="utf-8"), hypothesis)
    source_path.write_text(source, encoding="utf-8")
    agent.files[path] = source
    state_path = agent.workspace / "shared/reference_recalibration.json"
    before = json.loads(state_path.read_text()) if state_path.exists() else {}
    observation_start = len(agent.observations)
    checked_state = deepcopy(before)
    reused = _reuse_paid_family_exclusions(agent, laboratory, checked_state, source)
    paid_check = _paid_family_check(agent, laboratory, checked_state, hypothesis)
    if paid_check is not None or reused:
        state_path.write_text(json.dumps(checked_state, indent=2))
    excluded = paid_check is not None and paid_check["status"] == "UNSAT_VERIFIED"
    execution = ({"status": "method_stopped"} if excluded else
                 agent._run_procedure(laboratory, path, max_steps=256,
                                      query_arguments={"estimator_trial": True}))
    state = json.loads(state_path.read_text()) if state_path.exists() else {}
    observations = agent.observations[observation_start:]
    result = {"operator": "reference_hypothesis", "path": path,
              "hypothesis": hypothesis, "status": execution["status"],
              "reused_paid_family_exclusions": reused,
              "new_observation_indices": [record["index"] for record in observations],
              "new_observation_count": len(observations)}
    for key in ("tests", "fit_refutations", "out_of_range", "setting_recoveries", "response_constraints"):
        result[key] = deepcopy(state.get(key, [])[len(before.get(key, [])):])
    result["research_table"] = deepcopy(state.get("research_table", {}))
    result["prediction_selection"] = deepcopy(state.get("prediction_selection"))
    history_start = len(before.get("response_research_history", []))
    result["response_research_history"] = deepcopy(
        state.get("response_research_history", [])[history_start:])
    response = state.get("response_research", {}) if result["response_research_history"] else {}
    result["response_research"] = {key: deepcopy(response[key]) for key in (
        "status", "question_id", "selected_setting", "selected_number", "selection",
        "family_research", "evidence", "operational_fallback") if key in response}
    result["research_obligation"] = deepcopy(response.get("family_research", {}).get("research_obligation"))
    if paid_check is not None:
        result["paid_family_check"] = paid_check
    if excluded:
        result["reason"] = "Paid responses already exclude this basis with a shared connected activation band"
        result["research_obligation"] = {
            "reason": "proposed_shared_response_family_refuted",
            "question": "Which measurement or response structure revises the conflict in the paid responses?",
            "family": hypothesis["id"], "scope": paid_check["scope"],
            "evidence": paid_check["evidence"]}
    prefix = "reference_fit_" + hypothesis["id"] + "_"
    result["fitted_predictions"] = [
        {"question_id": question, **{key: deepcopy(relation[key])
            for key in ("status", "diagnosis", "selected_program", "selected_probe", "fit_evidence", "fit_rows", "empirical_prediction")
            if key in relation}}
        for question, relation in agent.relation_research.items() if question.startswith(prefix)]
    if state.get("test"):
        result["pending_test"] = deepcopy(state["test"])
    if execution.get("steps"):
        last = execution["steps"][-1].get("feedback", {})
        result.update({key: deepcopy(last[key]) for key in ("error", "reason") if key in last})
    return result
