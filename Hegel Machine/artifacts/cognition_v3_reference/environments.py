"""Interactive, reproducible development environments for cognitive research.

The controller sees only ``spec`` and ``observe``. Mechanism and relationship
labels live in evaluation metadata; evaluation trajectories are generated by a
separate random stream and are requested only after the controller has stopped.
"""

from __future__ import annotations

from dataclasses import dataclass
from math import isfinite
import random
from typing import Protocol

from .models import Observation, Probe, TaskSpec


class Environment(Protocol):
    spec: TaskSpec
    evaluation_metadata: dict[str, str]

    def observe(self, probe: Probe) -> list[Observation]: ...

    def evaluation_rows(self) -> tuple[Observation, ...]: ...


@dataclass(frozen=True)
class _Mechanism:
    kind: str
    slope: float = 1.0
    intercept: float = 0.0
    lag_weight: float = 0.0
    z_weight: float = 0.0
    noise_scale: float = 0.0
    lower_threshold: float = -0.5
    upper_threshold: float = 0.5
    history_lag: int = 1
    nonlinear_weight: float = 0.0
    interaction_weight: float = 0.0


def _probe(probe_id: str, xs: list[float], zs: list[float]) -> Probe:
    return Probe(
        probe_id=probe_id,
        sequence=tuple({"x": float(x), "z": float(z)} for x, z in zip(xs, zs)),
    )


def _query_catalog(seed: int) -> tuple[tuple[Probe, ...], tuple[Probe, ...]]:
    """Use the same available interventions for every mechanism in the suite."""
    rng = random.Random(seed)
    initial = tuple(
        _probe(f"initial_{index:02d}", [value] * 3, [value] * 3)
        for index, value in enumerate((-0.75, 0.25, 0.9))
    )
    sequences = [
        [-1.25] * 8,
        [1.25] * 8,
        [-1.25, -0.75, -0.25, 0.25, 0.75, 1.25, 0.25, -0.25],
        [1.25, 0.0, -1.25, 0.0, 1.25, 0.0, -1.25, 0.0],
        [0.0] * 8,
        [-1.0, 1.0, -0.5, 0.5, -1.25, 1.25, -0.25, 0.25],
        [-1.0, -1.0, 1.0, 1.0, -0.25, -0.25, 0.25, 0.25],
        [rng.uniform(-1.5, 1.5) for _ in range(8)],
        [-1.0, -0.25, 0.0, 0.25, 1.0, 0.25, 0.0, -0.25],
        [1.0, 0.25, 0.0, -0.25, -1.0, -0.25, 0.0, 0.25],
        [rng.uniform(-1.5, 1.5) for _ in range(8)],
        [rng.uniform(-1.5, 1.5) for _ in range(8)],
    ]
    available = []
    for index, xs in enumerate(sequences):
        zs = [rng.uniform(-1.5, 1.5) for _ in xs]
        if index in (0, 1, 4):
            zs = [-1.25, 1.25] * 4
        elif index == 5:
            zs = [0.0] * 8
        elif index == 6:
            zs = [-1.0, 1.0] * 4
        available.append(_probe(f"query_{index:02d}", xs, zs))
    return initial, tuple(available)


class TemporalEnvironment:
    """A bounded simulator whose probes reset the underlying process state.

    Repeating a registered probe returns the same observation sequence. Noise
    belongs to the seeded environment realization, so repeatedly asking the
    same question cannot obtain additional independent noise draws for free.
    """

    def __init__(
        self,
        *,
        task_id: str,
        seed: int,
        query_seed: int,
        mechanism: _Mechanism,
        phase: str,
        related_task: str = "",
        risk_quantile: float = 0.5,
        feature_names: tuple[str, str] = ("x", "z"),
        feature_limit: float = 1.5,
        partition: str = "development",
        decision_costs: tuple[float, float] | None = None,
    ) -> None:
        initial, available = _query_catalog(query_seed)
        if feature_names != ("x", "z"):
            def rename(probe: Probe) -> Probe:
                return Probe(probe.probe_id, tuple(
                    {feature_names[0]: row["x"], feature_names[1]: row["z"]}
                    for row in probe.sequence
                ))
            initial = tuple(rename(probe) for probe in initial)
            available = tuple(rename(probe) for probe in available)
        self.spec = TaskSpec(
            task_id=task_id,
            description=(
                "Predict the next scalar reading from the observed controls. "
                "Queries provide independent sequences; previous readings within "
                "a sequence remain available as history."
            ),
            feature_names=feature_names,
            initial_probes=initial,
            available_probes=available,
            risk_quantile=risk_quantile,
            context={
                "observation_unit": "dimensionless",
                "query_reset": "independent_sequence",
            },
            feature_bounds={name: (-feature_limit, feature_limit) for name in feature_names},
            max_probe_length=12,
            decision_costs=(decision_costs if decision_costs is not None else
                            (risk_quantile, 1.0 - risk_quantile) if risk_quantile != 0.5 else None),
        )
        self.evaluation_metadata = {
            "phase": phase,
            "mechanism": mechanism.kind,
            "related_task": related_task,
            "partition": partition,
        }
        self._seed = seed
        self._mechanism = mechanism
        self._feature_names = feature_names
        self._feature_limit = feature_limit
        self._probe_seeds = {
            self._probe_key(probe): seed * 1009 + index * 37
            for index, probe in enumerate((*initial, *available))
        }
        self._probe_rng = random.Random(seed + 3_000_017)

    def _probe_key(self, probe: Probe) -> tuple[tuple[float, ...], ...]:
        return tuple(tuple(float(row[name]) for name in self._feature_names) for row in probe.sequence)

    def _target(
        self,
        features: dict[str, float],
        history: list[dict[str, float]],
        rng: random.Random,
    ) -> float:
        mechanism = self._mechanism
        x = features[self._feature_names[0]]
        z = features[self._feature_names[1]]
        if mechanism.kind == "hysteresis":
            previous_target = history[-1]["__target__"] if history else 0.0
            return float(
                x >= mechanism.upper_threshold
                or (previous_target >= 0.5 and x >= mechanism.lower_threshold)
            )
        previous_x = (
            history[-mechanism.history_lag][self._feature_names[0]]
            if len(history) >= mechanism.history_lag else 0.0
        )
        prediction = (
            mechanism.slope * x
            + mechanism.intercept
            + mechanism.lag_weight * previous_x
            + mechanism.z_weight * z
            + mechanism.nonlinear_weight * x * x
            + mechanism.interaction_weight * x * z
        )
        if mechanism.kind == "tail_risk":
            scale = mechanism.noise_scale * (0.2 + abs(x))
            draw = rng.gauss(0.0, 1.0)
            if rng.random() < 0.12:
                draw = 3.0 + abs(draw)
            prediction += scale * draw
        elif mechanism.noise_scale:
            prediction += rng.gauss(0.0, mechanism.noise_scale)
        return prediction

    def _simulate(self, probe: Probe, seed: int) -> list[Observation]:
        rng = random.Random(seed)
        history: list[dict[str, float]] = []
        observations = []
        for supplied_features in probe.sequence:
            features = dict(supplied_features)
            target = self._target(features, history, rng)
            observations.append(
                Observation(
                    features=features,
                    target=target,
                    history=tuple(dict(row) for row in history),
                )
            )
            history.append({**features, "__target__": target})
        return observations

    def observe(self, probe: Probe) -> list[Observation]:
        if not 1 <= probe.cost <= self.spec.max_probe_length:
            raise ValueError("probe length is outside the published task limits")
        for row in probe.sequence:
            if set(row) != set(self.spec.feature_names):
                raise ValueError("probe controls must match the published features")
            for name, value in row.items():
                low, high = self.spec.feature_bounds[name]
                if not isfinite(value) or not low <= value <= high:
                    raise ValueError("probe control is outside its published bounds")
        key = self._probe_key(probe)
        if key not in self._probe_seeds:
            # Fresh interventions take the next independent simulator draw.
            # Repeated trajectories replay that realization without a digest.
            self._probe_seeds[key] = self._probe_rng.randrange(2**63)
        return self._simulate(probe, self._probe_seeds[key])

    def evaluation_rows(self) -> tuple[Observation, ...]:
        rng = random.Random(self._seed + 1_000_003)
        rows = []
        for index in range(24):
            probe = Probe(f"evaluation_{index:02d}", tuple(
                {name: rng.uniform(-self._feature_limit, self._feature_limit)
                 for name in self._feature_names}
                for _ in range(8)
            ))
            rows.extend(self._simulate(probe, self._seed + 2_000_003 + index))
        return tuple(rows)


def make_suite(seed: int = 7, partition: str = "development") -> list[Environment]:
    """Build a named public research sequence.

    These are public development generators. A new seed supplies new random
    inputs and noise. Confirmation reserves combinations, parameter intervals
    and history length three from the development generator; it is not an
    independently designed or independently custodied benchmark.
    """
    if partition == "confirmation":
        return _confirmation_suite(seed)
    if partition == "forward":
        return _forward_suite(seed)
    if partition != "development":
        raise ValueError("partition must be development, confirmation or forward")
    definitions = [
        ("acquire", "", _Mechanism("parameter", slope=1.4, intercept=0.3), 0.5),
        ("acquire", "", _Mechanism("history", slope=0.6, lag_weight=1.2), 0.5),
        ("acquire", "", _Mechanism("hysteresis"), 0.5),
        ("acquire", "", _Mechanism("tail_risk", slope=0.7, intercept=0.1, noise_scale=0.35), 0.9),
        ("acquire", "", _Mechanism("sparse", slope=1.2, intercept=0.2, noise_scale=0.02), 0.5),
        ("transfer", "t01", _Mechanism("parameter", slope=1.7, intercept=-0.1), 0.5),
        ("transfer", "t02", _Mechanism("history", slope=0.6, lag_weight=1.2, intercept=0.05), 0.5),
        ("transfer", "t03", _Mechanism("hysteresis"), 0.5),
        ("transfer", "t04", _Mechanism("tail_risk", slope=0.7, intercept=0.15, noise_scale=0.3), 0.9),
        ("transfer", "t05", _Mechanism("sparse", slope=1.2, intercept=0.2, noise_scale=0.02), 0.5),
        ("conflict", "t05", _Mechanism("feature_conflict", slope=1.2, intercept=0.2, z_weight=1.1), 0.5),
        ("conflict", "t02", _Mechanism("history_conflict", slope=1.3, intercept=0.6), 0.5),
    ]
    environments = [
        TemporalEnvironment(
            task_id=f"t{index + 1:02d}",
            seed=seed * 101 + index * 13,
            query_seed=seed,
            mechanism=mechanism,
            phase=phase,
            related_task=related_task,
            risk_quantile=quantile,
        )
        for index, (phase, related_task, mechanism, quantile) in enumerate(definitions)
    ]
    extras = [
        ("t13", "acquire", "", _Mechanism("nonlinear", slope=0.3, nonlinear_weight=0.9), ("x", "z")),
        ("t14", "acquire", "", _Mechanism("history_two", slope=0.6, lag_weight=1.2, history_lag=2), ("x", "z")),
        ("t15", "transfer", "t01", _Mechanism("renamed_parameter", slope=1.4, intercept=0.3), ("u", "v")),
        ("t16", "unrelated", "", _Mechanism("unrelated_interaction", slope=0.0, interaction_weight=1.1, intercept=-0.2), ("x", "z")),
        ("t02", "regime_change", "t02", _Mechanism("supported_scope_regime_change", slope=-1.3, intercept=0.6), ("x", "z")),
    ]
    for index, (task_id, phase, related, mechanism, names) in enumerate(extras, start=12):
        environments.append(TemporalEnvironment(
            task_id=task_id, seed=seed * 101 + index * 13, query_seed=seed,
            mechanism=mechanism, phase=phase, related_task=related, feature_names=names,
        ))
    return environments


def _confirmation_suite(seed: int) -> list[Environment]:
    rng = random.Random(seed + 4_000_037)
    slope = rng.uniform(2.1, 2.7)
    intercept = rng.uniform(-0.8, -0.5)
    definitions = [
        ("c01", "acquire", "", _Mechanism("parameter_interval", slope=slope, intercept=intercept), ("x", "z"), 0.5),
        ("c02", "acquire", "", _Mechanism("history_three", slope=0.4, lag_weight=1.6, history_lag=3), ("x", "z"), 0.5),
        ("c03", "acquire", "", _Mechanism("nonlinear", slope=0.5, nonlinear_weight=1.4), ("x", "z"), 0.5),
        ("c04", "acquire", "", _Mechanism("tail_risk", slope=1.8, intercept=-0.4, noise_scale=0.6), ("x", "z"), 0.95),
        ("c05", "acquire", "", _Mechanism("sparse", slope=2.4, intercept=-0.3, noise_scale=0.04), ("x", "z"), 0.5),
        ("c06", "transfer", "c01", _Mechanism("renamed_parameter", slope=slope, intercept=intercept), ("a", "b"), 0.5),
        ("c07", "transfer", "c02", _Mechanism("renamed_history_three", slope=0.4, lag_weight=1.6, history_lag=3), ("u", "v"), 0.5),
        ("c08", "composition", "c02", _Mechanism("nonlinear_history_composition", slope=0.3, lag_weight=0.8, history_lag=3, nonlinear_weight=1.2), ("x", "z"), 0.5),
        ("c09", "composition", "c03", _Mechanism("nonlinear_interaction_composition", slope=0.0, nonlinear_weight=0.8, interaction_weight=1.3), ("x", "z"), 0.5),
        ("c10", "unrelated", "", _Mechanism("hysteresis", lower_threshold=-0.9, upper_threshold=0.9), ("x", "z"), 0.5),
        ("c11", "conflict", "c05", _Mechanism("feature_conflict", slope=2.4, intercept=-0.3, z_weight=-1.6), ("x", "z"), 0.5),
        ("c02", "regime_change", "c02", _Mechanism("supported_scope_regime_change", slope=-2.2, intercept=0.8), ("x", "z"), 0.5),
    ]
    return [
        TemporalEnvironment(
            task_id=task_id, seed=seed * 103 + index * 17, query_seed=seed + 53,
            mechanism=mechanism, phase=phase, related_task=related, feature_names=names,
            feature_limit=2.0, risk_quantile=quantile, partition="confirmation",
            decision_costs=(0.95, 0.05) if quantile == 0.95 else None,
        )
        for index, (task_id, phase, related, mechanism, names, quantile) in enumerate(definitions)
    ]


def _forward_suite(seed: int) -> list[Environment]:
    """First-use v3 evaluation design, fixed before evaluating either agent.

    Combine signed effects, longer memory and renamed roles. This generator is
    public; its role is a new prospective partition after the earlier two
    partitions have informed development, not independent task custody.
    """
    rng = random.Random(seed + 5_000_041)
    slope = rng.uniform(-2.2, -1.8)
    intercept = rng.uniform(0.6, 1.0)
    delayed = rng.uniform(-1.35, -0.95)
    curvature = rng.uniform(-1.1, -0.7)
    interaction = rng.uniform(-1.2, -0.8)
    definitions = [
        ("f01", "acquire", "", _Mechanism("signed_parameter", slope=slope, intercept=intercept), ("x", "z"), 0.5),
        ("f02", "acquire", "", _Mechanism("history_four", slope=0.55, lag_weight=delayed, history_lag=4), ("x", "z"), 0.5),
        ("f03", "acquire", "", _Mechanism("signed_nonlinear", slope=1.0, nonlinear_weight=curvature), ("x", "z"), 0.5),
        ("f04", "acquire", "", _Mechanism("tail_risk", slope=-0.65, intercept=0.4, noise_scale=0.45), ("x", "z"), 0.9),
        ("f05", "acquire", "", _Mechanism("signed_interaction", slope=0.0, intercept=0.25, interaction_weight=interaction), ("x", "z"), 0.5),
        ("f06", "transfer", "f01", _Mechanism("renamed_signed_parameter", slope=slope, intercept=intercept), ("p", "q"), 0.5),
        ("f07", "transfer", "f02", _Mechanism("renamed_history_four", slope=0.55, lag_weight=delayed, history_lag=4), ("r", "s"), 0.5),
        ("f08", "composition", "f02", _Mechanism("signed_nonlinear_history", slope=0.2, lag_weight=delayed * 0.65, history_lag=4, nonlinear_weight=curvature * 0.8), ("x", "z"), 0.5),
        ("f09", "composition", "f05", _Mechanism("history_nonlinear_interaction", slope=0.35, lag_weight=-0.7, history_lag=2, nonlinear_weight=0.6, interaction_weight=interaction * 0.9), ("x", "z"), 0.5),
        ("f10", "unrelated", "", _Mechanism("hysteresis", lower_threshold=-0.65, upper_threshold=0.8), ("x", "z"), 0.5),
        ("f11", "conflict", "f01", _Mechanism("signed_feature_conflict", slope=slope, intercept=intercept, z_weight=1.15), ("x", "z"), 0.5),
        ("f02", "regime_change", "f02", _Mechanism("supported_delay_regime_change", slope=0.55, lag_weight=1.2, history_lag=2), ("x", "z"), 0.5),
    ]
    return [
        TemporalEnvironment(
            task_id=task_id, seed=seed * 107 + index * 19, query_seed=seed + 101,
            mechanism=mechanism, phase=phase, related_task=related, feature_names=names,
            feature_limit=2.25, risk_quantile=quantile, partition="forward",
        )
        for index, (task_id, phase, related, mechanism, names, quantile) in enumerate(definitions)
    ]
